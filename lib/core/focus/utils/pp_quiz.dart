/// react-web lib/pp-section4-tables.ts.
class PpSection4Table {
  final String paperCode;
  final String number;
  final String nameFr;
  final String nameEn;
  const PpSection4Table(this.paperCode, this.number, this.nameFr, this.nameEn);
  String label(bool en) => '$number ${en ? nameEn : nameFr}';
}

const kPpSection4Tables = <PpSection4Table>[
  PpSection4Table('S4Q01', '4.1', 'Permanents recensés', 'Permanent staff counted'),
  PpSection4Table('S4Q02', '4.2', 'Temporaires recensés', 'Temporary staff counted'),
  PpSection4Table('S4Q03', '4.3', 'Permanents recrutés', 'Permanent staff recruited'),
  PpSection4Table('S4Q04', '4.4', 'Temporaires recrutés', 'Temporary staff recruited'),
  PpSection4Table('S4Q05', '4.5', 'Recrutements — handicap', 'Recruitment — disability'),
  PpSection4Table('S4Q06', '4.6', 'Recrutements — vulnérables', 'Recruitment — vulnerable'),
