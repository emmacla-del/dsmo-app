// The Project / Programme preliminary quiz — the rules of react-web's
// ProjectProgramScopeQuiz.tsx and QuizSemantics.applyProjectProgramQuizSemantics,
// with the same stored shape (data['_scopeConfig']['projectProgram']), so a
// declaration started on one client can be finished on the other.
//
// Four questions: the Section 3 results recorded (or « aucun bénéficiaire »),
// permanent staff (table 4.1), temporary staff (4.2), recruitments and their
// categories (4.3–4.6). The answers set each Section 4 table's status
// (REPORTED / NONE); a closed table and an unticked result row are zeroed.
// The UI is screens/onefop/project_program_scope_quiz.dart.
// ══════════════════════════════════════════════════════════════

