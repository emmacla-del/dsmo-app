String ppTableLabel(String paperCode, bool en) {
  for (final t in kPpSection4Tables) {
    if (t.paperCode == paperCode) return t.label(en);
  }
  return paperCode;
}

/// The recruitment category that opens a recruitment table.
const kPpRecruitmentTable = {
  'S4Q03': 'permanent',
  'S4Q04': 'temporary',
  'S4Q05': 'disability',
  'S4Q06': 'vulnerable',
};

class PpScope {
  final String? completedAt;
  final bool noOutcomes;
  final List<String> outcomes;
  final bool? hasPermanentStaff;
  final bool? hasTemporaryStaff;
  final bool? hasRecruitment;
  final List<String> recruitmentTypes;

  const PpScope({
    this.completedAt,
    this.noOutcomes = false,
    this.outcomes = const [],
    this.hasPermanentStaff,
    this.hasTemporaryStaff,
    this.hasRecruitment,
    this.recruitmentTypes = const [],
  });

  Map<String, dynamic> toJson() => {
        'completedAt': completedAt,
        'noOutcomes': noOutcomes,
        'outcomes': outcomes,
        'hasPermanentStaff': hasPermanentStaff,
        'hasTemporaryStaff': hasTemporaryStaff,
        'hasRecruitment': hasRecruitment,
        'recruitmentTypes': recruitmentTypes,
      };
}

/// The saved answers (data['_scopeConfig']['projectProgram']), or null.
Map<String, dynamic>? savedPpConfig(Map<String, dynamic> data) {
  final raw = data['_scopeConfig'];
  if (raw is Map && raw.containsKey('projectProgram')) {
    final c = raw['projectProgram'];
    return c is Map ? Map<String, dynamic>.from(c) : <String, dynamic>{};
  }
  return null;
}

/// Whether the quiz was confirmed (react-web: `completedAt` set).
bool isPpQuizConfirmed(Map<String, dynamic> data) =>
    savedPpConfig(data)?['completedAt'] != null;

List<String> _strings(dynamic v) =>
    v is List ? v.map((e) => e.toString()).toList() : const [];

/// The quiz's starting answers: what was saved, or else what the tables
/// already say (react-web initialConfig).
PpScope initialPpScope(Map<String, dynamic> data) {
  final cfg = savedPpConfig(data);
  if (cfg != null) {
    bool? b(String k) => cfg[k] is bool ? cfg[k] as bool : null;
    return PpScope(
      completedAt: cfg['completedAt']?.toString(),
      noOutcomes: cfg['noOutcomes'] == true,
      outcomes: _strings(cfg['outcomes']),
      hasPermanentStaff: b('hasPermanentStaff'),
      hasTemporaryStaff: b('hasTemporaryStaff'),
      hasRecruitment: b('hasRecruitment'),
      recruitmentTypes: _strings(cfg['recruitmentTypes']),
    );
  }

  // Heuristics from the data already there.
  final s1q15 = num.tryParse('${data['PP_S1Q15'] ?? data['s1q15'] ?? ''}');
  final bool? hasPermHeuristic = s1q15 != null && s1q15 > 0 ? true : null;
  dynamic status(String code) =>
      data['${code}_RESPONSE_STATUS'] ?? data['PP_${code}_RESPONSE_STATUS'];
  final s1 = status('S4Q01'), s2 = status('S4Q02'), s3 = status('S4Q03');
  final s4 = status('S4Q04'), s5 = status('S4Q05'), s6 = status('S4Q06');

  final hasPerm = s1 == 'REPORTED' ? true : s1 == 'NONE' ? false : hasPermHeuristic;
  final bool? hasTemp = s2 == 'REPORTED' ? true : s2 == 'NONE' ? false : null;
  final anyRecruitReported = [s3, s4, s5, s6].any((s) => s == 'REPORTED');
  final allRecruitNone = [s3, s4, s5, s6].every((s) => s == 'NONE');
  final bool? hasRec = anyRecruitReported ? true : allRecruitNone ? false : null;
  final recTypes = <String>[
    if (s3 == 'REPORTED') 'permanent',
    if (s4 == 'REPORTED') 'temporary',
    if (s5 == 'REPORTED') 'disability',
    if (s6 == 'REPORTED') 'vulnerable',
  ];

  // An outcome row counts as answered when any of its three periods holds
  // a figure — a forecast alone is not « aucun bénéficiaire ».
  final detected = <String>[
    for (final k in kPpOutcomeKeys)
      if (['current', 'outlook_dec', 'outlook_june'].any((p) {
        final v = data['s3kpi_${k}_$p'];
        return v != null && v != '' && v != 0 && v != '0';
      }))
        k,
  ];

  return PpScope(
    noOutcomes: detected.isEmpty && (s1 != null || s3 != null),
    outcomes: detected,
    hasPermanentStaff: hasPerm,
    hasTemporaryStaff: hasTemp,
    hasRecruitment: hasRec,
    recruitmentTypes: recTypes,
  );
}

bool ppQuizComplete(PpScope c) =>
    (c.noOutcomes || c.outcomes.isNotEmpty) &&
    c.hasPermanentStaff != null &&
    c.hasTemporaryStaff != null &&
    (c.hasRecruitment == false ||
        (c.hasRecruitment == true && c.recruitmentTypes.isNotEmpty));

/// The beats, in order.
enum PpBeat { outcomes, permanent, temporary, recruitment, recruitmentTypes }

PpBeat firstOpenPpBeat(PpScope c) {
  if (!(c.noOutcomes || c.outcomes.isNotEmpty)) return PpBeat.outcomes;
  if (c.hasPermanentStaff == null) return PpBeat.permanent;
  if (c.hasTemporaryStaff == null) return PpBeat.temporary;
  if (c.hasRecruitment == null) return PpBeat.recruitment;
  if (c.hasRecruitment == true && c.recruitmentTypes.isEmpty) {
    return PpBeat.recruitmentTypes;
  }
  return PpBeat.outcomes;
}

List<PpBeat> ppBeatOrder(PpScope c) => [
      PpBeat.outcomes,
      PpBeat.permanent,
      PpBeat.temporary,
      PpBeat.recruitment,
      if (c.hasRecruitment == true) PpBeat.recruitmentTypes,
    ];

bool ppBeatComplete(PpBeat beat, PpScope c) => switch (beat) {
      PpBeat.outcomes => c.noOutcomes || c.outcomes.isNotEmpty,
      PpBeat.permanent => c.hasPermanentStaff != null,
      PpBeat.temporary => c.hasTemporaryStaff != null,
      PpBeat.recruitment => c.hasRecruitment != null,
      PpBeat.recruitmentTypes => c.recruitmentTypes.isNotEmpty,
    };

/// True when these answers open this Section 4 table.
bool ppTableIsOpen(String paperCode, PpScope c) {
  switch (paperCode) {
    case 'S4Q01':
      return c.hasPermanentStaff == true;
    case 'S4Q02':
      return c.hasTemporaryStaff == true;
  }
  final type = kPpRecruitmentTable[paperCode];
  return type != null && c.hasRecruitment == true && c.recruitmentTypes.contains(type);
}

/// No results, no staff, no recruitment: a nil declaration.
bool isPpGlobalNone(PpScope c) =>
    c.noOutcomes &&
    c.hasPermanentStaff == false &&
    c.hasTemporaryStaff == false &&
    c.hasRecruitment == false;

/// Figures already typed in a table or result row these answers close
/// (react-web hasDroppedDataWarning).
bool ppHasDroppedData(PpScope c, Map<String, dynamic> data) {
  for (final t in kPpSection4Tables) {
    if (ppTableIsOpen(t.paperCode, c)) continue;
    final lower = t.paperCode.toLowerCase();
    final keys = keysMatchingPrefixes(data, ['pp_${lower}_', '${lower}_']);
    if (keys.any((k) => isEnteredCellData(data[k]))) return true;
  }
  for (final ok in kPpOutcomeKeys) {
    if (c.noOutcomes || !c.outcomes.contains(ok)) {
      if (isEnteredCellData(data['s3kpi_${ok}_current'])) return true;
    }
  }
  return false;
}

/// Applies the confirmed answers to the submission payload, as react-web
/// applyProjectProgramQuizSemantics: both status keys of each Section 4
/// table, zeros in closed tables and unticked result rows, and the quiz's
/// own keys left out. [tableCells] gives a table's cell ids by paper code.
Map<String, dynamic> applyPpQuizSemantics(
    Map<String, dynamic> payload, List<String> Function(String paperCode) tableCells) {
  final out = Map<String, dynamic>.from(payload);
  final cfg = savedPpConfig(payload);
  if (cfg != null && cfg['completedAt'] != null) {
    final c = initialPpScope(payload);
    final active = c.noOutcomes ? const <String>[] : c.outcomes;
    for (final ok in kPpOutcomeKeys) {
      if (!active.contains(ok)) out['s3kpi_${ok}_current'] = 0;
    }
    for (final t in kPpSection4Tables) {
      final status = ppTableIsOpen(t.paperCode, c) ? 'REPORTED' : 'NONE';
      out['${t.paperCode}_RESPONSE_STATUS'] = status;
      out['PP_${t.paperCode}_RESPONSE_STATUS'] = status;
      if (status == 'NONE') {
        for (final id in tableCells(t.paperCode)) {
          out[id] = 0;
        }
      }
    }
  }
  out.remove('_scopeConfig');
  out.remove('_scopeCsp');
  out.remove('_scopeAge');
  return out;
}
